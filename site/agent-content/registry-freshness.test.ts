// registry-freshness.test.ts: the committed `registry.gen.ts` (full records) and `registry.runtime.gen.ts`
// (the browser projection) equal what scripts/generate-agent-content.mjs produces from the tree today, byte
// for byte, the manifests carry the registry's `seedVersion`, and the tree passes the schema validator. A red names its
// own fix: `node scripts/generate-agent-content.mjs`. The negative controls run in memory, never by
// mutating the tree, so the equality and the empty problem list cannot pass vacuously.
import { describe, it, expect } from 'vitest'
// @ts-expect-error - node:fs is typed via @types/node; vitest/node resolves it at runtime (site/tsconfig.json carries no node types)
import { existsSync, readFileSync } from 'node:fs'
import { discoverAgentContent, generateRegistryModule, generateRuntimeModule, manifestUpdates, OUT_REGISTRY, OUT_RUNTIME } from '../../scripts/generate-agent-content.mjs'
import { digestInput, runtimeRecord, validateContent, type ContentRecord, type PersonaRecord, type PackRecord, type EntryRecord } from './schema.ts'
import { sha256 } from './digest.ts'
import { AGENT_CONTENT } from './registry.gen.ts'
import { AGENT_CONTENT_RUNTIME } from './registry.runtime.gen.ts'

declare const process: { cwd(): string }

const HEADER = '// GENERATED by scripts/generate-agent-content.mjs. DO NOT EDIT: run node scripts/generate-agent-content.mjs'
const committed = readFileSync(`${process.cwd()}/${OUT_REGISTRY}`, 'utf8') as string
const committedRuntime = readFileSync(`${process.cwd()}/${OUT_RUNTIME}`, 'utf8') as string
const discovered = discoverAgentContent()
const records = (): ContentRecord[] => JSON.parse(JSON.stringify(discovered.records)) as ContentRecord[]
const persona = (rs: ContentRecord[], id: string): PersonaRecord => rs.find((r): r is PersonaRecord => r.kind === 'persona' && r.id === id)!
const pack = (rs: ContentRecord[], id: string): PackRecord => rs.find((r): r is PackRecord => r.kind === 'pack' && r.id === id)!

describe('agent-content registry: freshness and schema', () => {
  it('both committed modules carry the GENERATED header', () => {
    expect(committed.split('\n')[0]).toBe(HEADER)
    expect(committedRuntime.split('\n')[0]).toBe(HEADER)
  })

  it('the committed modules equal a fresh generation', () => {
    expect(committed, 'stale registry.gen.ts: run node scripts/generate-agent-content.mjs and commit the result').toBe(generateRegistryModule(discovered.records))
    expect(committedRuntime, 'stale registry.runtime.gen.ts: run node scripts/generate-agent-content.mjs and commit the result').toBe(generateRuntimeModule(discovered.records))
  })

  it('the imported registries are the generated records and their runtime projection', () => {
    expect(JSON.parse(JSON.stringify(AGENT_CONTENT))).toEqual(JSON.parse(JSON.stringify(discovered.records)))
    expect(JSON.parse(JSON.stringify(AGENT_CONTENT_RUNTIME))).toEqual(JSON.parse(JSON.stringify(discovered.records.map(runtimeRecord))))
  })

  it('the runtime projection carries no path, digest, changelog or notes', () => {
    for (const r of AGENT_CONTENT_RUNTIME) {
      expect(Object.keys(r)).not.toContain('path')
      expect(Object.keys(r)).not.toContain('digest')
      expect(Object.keys(r.frontmatter)).not.toContain('changelog')
      expect(Object.keys(r.frontmatter)).not.toContain('notes')
    }
    expect(committed).toContain('"changelog"')
    expect(committedRuntime).not.toContain('"changelog"')
  })

  it('indexes 16 personas and the authored packs; the a2ui prompt files are not copied', () => {
    expect(discovered.records.filter((r) => r.kind === 'persona')).toHaveLength(16)
    expect(discovered.records.filter((r) => r.kind === 'pack').length).toBeGreaterThanOrEqual(9)
    expect(discovered.records.every((r) => r.path.startsWith('site/agent-content/'))).toBe(true)
  })

  it('a record digest is the sha256 of its digestInput, not of the file bytes', () => {
    const r = discovered.records.find((x) => x.kind === 'persona' && x.id === 'quant')!
    expect(r.digest).toBe(sha256(digestInput(r.frontmatter, r.body)))
    expect(r.digest).not.toBe(sha256(readFileSync(`${process.cwd()}/${r.path}`, 'utf8') as string))
  })

  it('every agent manifest carries the registry seedVersion', () => {
    const { updates, problems } = manifestUpdates(discovered.records)
    expect(problems).toEqual([])
    expect(updates).toHaveLength(15)
    for (const { path, text } of updates) expect(readFileSync(`${process.cwd()}/${path}`, 'utf8'), `stale ${path}: run node scripts/generate-agent-content.mjs`).toBe(text)
  })

  it('the content root AGENTS.md exists and produces no registry row (ACS-R15)', () => {
    expect(existsSync(`${process.cwd()}/site/agent-content/AGENTS.md`)).toBe(true)
    expect(discovered.records.some((r) => r.path.endsWith('AGENTS.md'))).toBe(false)
  })

  it('the real tree has no schema problems', () => {
    expect(validateContent(discovered.records)).toEqual([])
    expect(discovered.problems).toEqual([])
  })

  it('bites: a planted body byte changes the generated module', () => {
    const rs = records()
    persona(rs, 'quant').body += 'x'
    expect(generateRegistryModule(rs)).not.toBe(committed)
  })

  it('bites: a ref to a missing entry', () => {
    const rs = records()
    persona(rs, 'travel').frontmatter.skills.push('no-such-skill@1')
    expect(validateContent(rs).join('\n')).toContain('no-such-skill@1 names no skill')
  })

  it('bites: a ref at the wrong version', () => {
    const rs = records()
    const fm = persona(rs, 'travel').frontmatter
    fm.skills = fm.skills.map((ref) => ref.replace(/@1$/, '@2'))
    expect(validateContent(rs).some((p) => p.includes('at that version'))).toBe(true)
  })

  it('bites: an unknown frontmatter key', () => {
    const rs = records()
    ;(persona(rs, 'quant').frontmatter as unknown as Record<string, unknown>)['temperature'] = 0.7
    expect(validateContent(rs).join('\n')).toContain('unknown key temperature')
  })

  it('bites: a persona without a Surface style section', () => {
    const rs = records()
    const p = persona(rs, 'quant')
    p.body = p.body.split('\n\n## ')[0]!
    expect(validateContent(rs).join('\n')).toContain('no ## Surface style section')
  })

  it('bites: a duplicate section is a listed problem with its path, never a throw', () => {
    const rs = records()
    const p = persona(rs, 'quant')
    p.body = `${p.body}\n\n## Surface style\n\nagain`
    let problems: string[] = []
    expect(() => {
      problems = validateContent(rs)
    }).not.toThrow()
    expect(problems).toContain(`${p.path}: duplicate section Surface style`)
  })

  it('bites: a root entry no pack offers', () => {
    const rs = records()
    const games = pack(rs, 'games')
    games.frontmatter.entries = games.frontmatter.entries!.filter((ref) => ref !== 'quest-log@1')
    expect(validateContent(rs).join('\n')).toContain('a root entry no pack offers')
  })

  it('bites: a persona-local entry its persona never references', () => {
    const rs = records()
    const p = persona(rs, 'croupier')
    p.frontmatter.tools = []
    expect(validateContent(rs).join('\n')).toContain('croupier never references this entry')
  })

  it('bites: an invocable root entry (a library add carries no availability)', () => {
    const rs = records()
    rs.find((r): r is EntryRecord => r.kind === 'skill' && r.id === 'menu-card')!.frontmatter.availability = 'invocable'
    expect(validateContent(rs).join('\n')).toContain('a root entry is context')
  })

  it('bites: an entry whose name is not its folder', () => {
    const rs = records()
    const e = rs.find((r): r is EntryRecord => r.kind === 'skill' && r.id === 'menu-card')!
    e.frontmatter.name = 'menu'
    expect(validateContent(rs).join('\n')).toContain('name menu is not the folder name menu-card')
  })
})
