#!/usr/bin/env node
// generate-agent-assets.mjs: embeds the a2ui `./agent` toolkit's file assets as committed TypeScript
// modules, so the toolkit can read them without `node:fs` at a `process.cwd()`-relative path.
//
// Two outputs, both under packages/agent-ui/a2ui/src/agent/:
//   assets.gen.ts         AGENT_ASSETS: every prompt `.md` and every catalog `selection.json`, keyed by
//                         POSIX path relative to packages/agent-ui/a2ui/src/, content read as utf8, never
//                         normalized.
//   dogfood-fleet.gen.ts  DOGFOOD_FLEET: the dogfood inventory rows, derived from every
//                         components/src/controls/*/ folder by `deriveDogfoodFleet` (dogfood-descriptor.ts).
//
// Discovery is by rule, never a list: a new prompt, sidecar or control folder is picked up on the next run.
//
// Usage:
//   node scripts/generate-agent-assets.mjs           write both outputs
//   node scripts/generate-agent-assets.mjs --check   write nothing; exit 1 naming each stale output
//
// Every export is write-free so `agent-assets-freshness.test.ts` regenerates with the IDENTICAL routine
// and compares against the committed files. Paths resolve from `process.cwd()`, never `import.meta.url`:
// the jsdom `packages` vitest project does not hand this module a `file:` URL (the
// scripts/build-dogfood-assets.mjs precedent). Node 24 strips the types of the imported `.ts` module (the
// scripts/generate-props.mjs precedent).
//
// Emitted values are `JSON.stringify` output with every single quote, U+2028 and U+2029 rewritten as a
// `\uXXXX` escape: the same string at run time, and no embedded text can read as an import specifier or a
// column-0 call to the raw-text scanners (gates.test.ts, publish-packages.mjs, side-effects.test.mjs).

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { deriveDogfoodFleet } from '../packages/agent-ui/a2ui/src/agent/dogfood-descriptor.ts'

const SRC_DIR = 'packages/agent-ui/a2ui/src'
const PROMPTS_KEY = 'agent/prompts'
const CATALOG_KEY = 'catalog'
const CONTROLS_DIR = 'packages/agent-ui/components/src/controls'
const SIDECAR_NAME = 'selection.json'
const REGEN = 'node scripts/generate-agent-assets.mjs'

/** Repo-relative output paths. */
export const OUT_ASSETS = `${SRC_DIR}/agent/assets.gen.ts`
export const OUT_FLEET = `${SRC_DIR}/agent/dogfood-fleet.gen.ts`

const HEADER = `// GENERATED by scripts/generate-agent-assets.mjs. DO NOT EDIT: run ${REGEN}`

/** Every file under `absDir` (recursive, name-sorted) whose name passes `pick`, as `relDir`-prefixed POSIX
 *  paths. */
function walk(absDir, relDir, pick, out = []) {
  for (const name of readdirSync(absDir).sort()) {
    const abs = `${absDir}/${name}`
    const rel = `${relDir}/${name}`
    if (statSync(abs).isDirectory()) walk(abs, rel, pick, out)
    else if (pick(name)) out.push(rel)
  }
  return out
}

/** Every directory directly under components/src/controls/, as raw text: its `.md` descriptors in name
 *  order and its non-test `.ts` sources one level deep (a nested directory is never read). */
export function readControlFolders(root = process.cwd()) {
  const controlsDir = `${root}/${CONTROLS_DIR}`
  const folders = []
  for (const dirName of readdirSync(controlsDir).sort()) {
    const dirPath = `${controlsDir}/${dirName}`
    if (!statSync(dirPath).isDirectory()) continue
    const fileNames = readdirSync(dirPath).sort()
    const read = (n) => readFileSync(`${dirPath}/${n}`, 'utf8')
    folders.push({
      descriptors: fileNames.filter((n) => n.endsWith('.md')).map(read),
      sources: fileNames.filter((n) => n.endsWith('.ts') && !n.endsWith('.test.ts')).map(read),
    })
  }
  return folders
}

/** The one discovery: every `*.md` under the prompts directory and every `selection.json` under the
 *  catalog directory (both recursive), plus the dogfood fleet rows derived from the control folders. */
export function discoverAgentAssets(root = process.cwd()) {
  const srcDir = `${root}/${SRC_DIR}`
  const paths = [
    ...walk(`${srcDir}/${PROMPTS_KEY}`, PROMPTS_KEY, (n) => n.endsWith('.md')),
    ...walk(`${srcDir}/${CATALOG_KEY}`, CATALOG_KEY, (n) => n === SIDECAR_NAME),
  ].sort()
  const text = paths.map((path) => ({ path, content: readFileSync(`${srcDir}/${path}`, 'utf8') }))
  return { text, fleet: deriveDogfoodFleet(readControlFolders(root)) }
}

/** A JS string/array/object literal for `value`: JSON, with `'`, U+2028 and U+2029 escaped. */
function literal(value) {
  return JSON.stringify(value).replace(/'/g, '\\u0027').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029')
}

/** Both module sources for `discovered` (pure, deterministic: keys in default sort order, rows in tag
 *  order). */
export function generateAgentAssetsModules(discovered) {
  const byPath = new Map(discovered.text.map((a) => [a.path, a.content]))
  const assetLines = [...byPath.keys()].sort().map((key) => `  ${literal(key)}: ${literal(byPath.get(key))},`)
  const assets = [
    HEADER,
    `// Discovery: every *.md under ${SRC_DIR}/${PROMPTS_KEY}/ and every ${SIDECAR_NAME} under ${SRC_DIR}/${CATALOG_KEY}/, recursive, keyed by path relative to ${SRC_DIR}/.`,
    'export const AGENT_ASSETS: Readonly<Record<string, string>> = Object.freeze({',
    ...assetLines,
    '})',
    '',
  ].join('\n')
  const rows = [...discovered.fleet]
    .sort((a, b) => a.tag.localeCompare(b.tag))
    .map((r) => `  ${literal({ tag: r.tag, summary: r.summary, attrs: r.attrs, siblings: [...r.siblings] })},`)
  const fleet = [
    HEADER,
    `// Discovery: one row per tagged *.md descriptor in each directory under ${CONTROLS_DIR}/, derived by deriveDogfoodFleet, sorted by tag.`,
    "import type { DogfoodControl } from './dogfood-descriptor.ts'",
    'export const DOGFOOD_FLEET: readonly DogfoodControl[] = [',
    ...rows,
    ']',
    '',
  ].join('\n')
  return { assets, fleet }
}

function main(args) {
  const root = process.cwd()
  const { assets, fleet } = generateAgentAssetsModules(discoverAgentAssets(root))
  const outputs = [
    [OUT_ASSETS, assets],
    [OUT_FLEET, fleet],
  ]
  if (args.includes('--check')) {
    const stale = outputs.filter(([path, src]) => !existsSync(`${root}/${path}`) || readFileSync(`${root}/${path}`, 'utf8') !== src)
    for (const [path] of stale) console.error(`generate-agent-assets: ${path} is stale; run ${REGEN}`)
    if (stale.length > 0) process.exitCode = 1
    return
  }
  for (const [path, src] of outputs) {
    writeFileSync(`${root}/${path}`, src)
    console.log(`generate-agent-assets: wrote ${src.length} chars to ${path}`)
  }
}

if (process.argv[1]?.endsWith('generate-agent-assets.mjs')) main(process.argv.slice(2))
