// scripts/e2e-admin/probe/scenarios/round.ts: live round 2 (T-0225). Every preset's scenarios x its models,
// sample 1, as one `live-commands.sh` in `.sdlc/live-round-2/`: Croupier on Haiku, Sonnet and Opus 5.5, the
// Concierge, Lexicographer and Admiral on Haiku and Sonnet 5.5. The file runs Haiku first, then Sonnet, then
// Opus, so a stop at the spend cap (`../run-capped.ts`) leaves the cheap cells filled. `round.test.mjs` pins
// the file to this generator.
//
// Run `node --experimental-strip-types scripts/e2e-admin/probe/scenarios/round.ts` to print the script.

import type { ProbeStep } from '../model.ts'
import { ADMIRAL_MODELS, ADMIRAL_SCENARIOS } from './admiral.ts'
import { CONCIERGE_MODELS, CONCIERGE_SCENARIOS } from './concierge.ts'
import { CROUPIER_MODELS, CROUPIER_ROUND_SCENARIOS, quote } from './croupier.ts'
import { LEXICOGRAPHER_MODELS, LEXICOGRAPHER_SCENARIOS } from './lexicographer.ts'

export interface RoundScenario {
  name: string
  /** A step's own `expect` becomes `--expect-turn` after it. */
  steps: ProbeStep[]
  /** Run-level `--expect-component`: some turn ships each type. */
  expectComponents: string[]
}

export interface RoundModel {
  id: string
  short: string
}

export interface RoundPreset {
  /** The preset id (`--agent`). */
  agent: string
  scenarios: readonly RoundScenario[]
  models: readonly RoundModel[]
}

export const ROUND_PRESETS: readonly RoundPreset[] = [
  { agent: 'croupier', scenarios: CROUPIER_ROUND_SCENARIOS, models: CROUPIER_MODELS },
  { agent: 'concierge', scenarios: CONCIERGE_SCENARIOS, models: CONCIERGE_MODELS },
  { agent: 'lexicographer', scenarios: LEXICOGRAPHER_SCENARIOS, models: LEXICOGRAPHER_MODELS },
  { agent: 'admiral', scenarios: ADMIRAL_SCENARIOS, models: ADMIRAL_MODELS },
]

/** Spend order: the round's script runs every Haiku cell, then Sonnet, then Opus. */
export const MODEL_ORDER = ['haiku', 'sonnet', 'opus'] as const
export const ROUND_SAMPLE = 1
export const ROUND_RUNS_DIR = '.sdlc/live-round-2/runs'

/** The probe argv for one preset x scenario x model; out dir `runs/<preset>-<scenario>-<model>-<sample>`. */
export function roundArgv(agent: string, scenario: RoundScenario, model: RoundModel, sample = ROUND_SAMPLE): string[] {
  const name = `${agent}-${scenario.name}-${model.short}-${sample}`
  return [
    '--agent', agent,
    '--model', model.id,
    ...scenario.steps.flatMap((s) => [...('say' in s ? ['--say', s.say] : 'click' in s ? ['--click', s.click] : []), ...(s.expect ?? []).flatMap((c) => ['--expect-turn', c])]),
    ...scenario.expectComponents.flatMap((c) => ['--expect-component', c]),
    '--out', `${ROUND_RUNS_DIR}/${name}`,
    '--name', name,
  ]
}

/** Every run of the round in script order: by model (Haiku, Sonnet, Opus), then preset, then scenario. */
export function roundRuns(): Array<{ agent: string; scenario: RoundScenario; model: RoundModel; argv: string[] }> {
  return MODEL_ORDER.flatMap((short) =>
    ROUND_PRESETS.flatMap((p) => p.models.filter((m) => m.short === short).flatMap((model) => p.scenarios.map((scenario) => ({ agent: p.agent, scenario, model, argv: roundArgv(p.agent, scenario, model) })))),
  )
}

/** `.sdlc/live-round-2/live-commands.sh`. */
export function roundCommandsScript(): string {
  const lines = [
    '#!/usr/bin/env bash',
    '# T-0225 live round 2. Generated by',
    '# `node --experimental-strip-types scripts/e2e-admin/probe/scenarios/round.ts`; do not hand-edit.',
    '# Spends API credit through the dev proxy (key in .env, never printed). Cap: $20 in total (Kim 2026-10-14).',
    '# Run it through the capped runner, which stops at the cap and skips a run whose report.json exists:',
    '#   node --experimental-strip-types scripts/e2e-admin/probe/run-capped.ts .sdlc/live-round-2/live-commands.sh --cap 20',
    '# Haiku 5.5 first, then Sonnet 5.5, then Opus 5.5 (Croupier only); sample 1. A probe exits 1 when a check fails.',
  ]
  let current = ''
  for (const run of roundRuns()) {
    if (run.model.id !== current) {
      current = run.model.id
      lines.push('', `# ${current}`)
    }
    lines.push(['npm', 'run', 'chat:probe', '--', ...run.argv].map(quote).join(' '))
  }
  return `${lines.join('\n')}\n`
}

if (import.meta.url === `file://${process.argv[1]}`) process.stdout.write(roundCommandsScript())
