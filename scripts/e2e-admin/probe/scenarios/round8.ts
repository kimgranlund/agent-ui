// scripts/e2e-admin/probe/scenarios/round8.ts: live round 8 (T-0319), the full matrix again after the round 6 and 7
// fixes (T-0296 to T-0305), the settings pane (T-0306), the stale-surface sweep (T-0307) and the routing review rulings
// (T-0308 to T-0317). One `live-commands.sh` in `.sdlc/evals/rounds/2026-10-16-r8-matrix/` holding round 6's 87 runs:
// same scenarios, models, names and order (every Haiku run, then Sonnet, then Opus), regenerated from the current
// `round6.ts`, so a stop at the $42 spend cap (`../run-capped.ts`) drops Opus first (Kim 2026-10-16).
//
// The expected spend is round 6's ledger spend per model (`R6_MODEL_COST`, from
// `.sdlc/evals/rounds/2026-10-15-r6-matrix/ledger.jsonl`).
//
// Run `node --experimental-strip-types scripts/e2e-admin/probe/scenarios/round8.ts` to print the script;
// `round8.test.mjs` pins the file to this generator.

import { quote } from '../model.ts'
import { round6Runs, type Round6Run } from './round6.ts'

export const ROUND8_DIR = '.sdlc/evals/rounds/2026-10-16-r8-matrix'
export const ROUND8_FILE = `${ROUND8_DIR}/live-commands.sh`
export const ROUND8_CAP = 42

/** Round 6 ledger `costUsd` summed per model, the spend estimate. */
export const R6_MODEL_COST: Readonly<Record<string, number>> = {
  'claude-haiku-5-5': 0.845729,
  'claude-sonnet-5-5': 12.491774,
  'claude-opus-5-5': 23.481264,
}

const retarget = (argv: string[], name: string): string[] => argv.map((a, i) => (argv[i - 1] === '--out' ? `${ROUND8_DIR}/runs/${name}` : a))

/** Every round 6 run in its order, out under the round 8 folder. */
export function round8Runs(): Round6Run[] {
  return round6Runs().map((r) => ({ ...r, argv: retarget(r.argv, r.name) }))
}

/** Sum of round 6's per-model spend, the expected spend. */
export function round8ExpectedUsd(): number {
  return Object.values(R6_MODEL_COST).reduce((sum, c) => sum + c, 0)
}

/** `.sdlc/evals/rounds/2026-10-16-r8-matrix/live-commands.sh`. */
export function round8CommandsScript(): string {
  const lines = [
    '#!/usr/bin/env bash',
    "# T-0319 live round 8: round 6's full matrix again, every preset scenario, the routing pack and the long flows on",
    '# three models. Generated by `node --experimental-strip-types scripts/e2e-admin/probe/scenarios/round8.ts`; do not hand-edit.',
    `# Spends API credit through the dev proxy (key in .env, never printed). Cap: $${ROUND8_CAP} in total (Kim 2026-10-16).`,
    `#   node --experimental-strip-types scripts/e2e-admin/probe/run-capped.ts --describe ${ROUND8_FILE}`,
    `#   node --experimental-strip-types scripts/e2e-admin/probe/run-capped.ts ${ROUND8_FILE} --cap ${ROUND8_CAP} --round r8-matrix`,
    `# Haiku 5.5 first, then Sonnet 5.5, then Opus 5.5 (expected about $${round8ExpectedUsd().toFixed(2)}, round 6's spend); sample 1.`,
    '# A probe exits 1 when a check fails.',
  ]
  let current = ''
  for (const run of round8Runs()) {
    if (run.model.id !== current) {
      current = run.model.id
      lines.push('', `# ${current}`)
    }
    lines.push(['npm', 'run', 'chat:probe', '--', ...run.argv].map(quote).join(' '))
  }
  return `${lines.join('\n')}\n`
}

if (import.meta.url === `file://${process.argv[1]}`) process.stdout.write(round8CommandsScript())
