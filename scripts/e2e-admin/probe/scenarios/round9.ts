// scripts/e2e-admin/probe/scenarios/round9.ts: live round 9 (T-0326), the full matrix again after the round 8 fixes
// (T-0320 to T-0325). One `live-commands.sh` in `.sdlc/evals/rounds/2026-10-17-r9-matrix/` holding round 8's 87 runs:
// same scenarios, models, names and order (every Haiku run, then Sonnet, then Opus), regenerated from the current
// `round8.ts` (so the hold'em steps carry T-0325's fix), and a stop at the $42 spend cap (`../run-capped.ts`) drops
// Opus first (Kim 2026-10-17).
//
// The expected spend is round 8's ledger spend per model (`R8_MODEL_COST`, from
// `.sdlc/evals/rounds/2026-10-16-r8-matrix/ledger.jsonl`).
//
// Run `node --experimental-strip-types scripts/e2e-admin/probe/scenarios/round9.ts` to print the script;
// `round9.test.mjs` pins the file to this generator.

import { quote } from '../model.ts'
import type { Round6Run } from './round6.ts'
import { round8Runs } from './round8.ts'

export const ROUND9_DIR = '.sdlc/evals/rounds/2026-10-17-r9-matrix'
export const ROUND9_FILE = `${ROUND9_DIR}/live-commands.sh`
export const ROUND9_CAP = 42

/** Round 8 ledger `costUsd` summed per model, the spend estimate. */
export const R8_MODEL_COST: Readonly<Record<string, number>> = {
  'claude-haiku-5-5': 0.76266,
  'claude-sonnet-5-5': 12.943312,
  'claude-opus-5-5': 22.46951,
}

const retarget = (argv: string[], name: string): string[] => argv.map((a, i) => (argv[i - 1] === '--out' ? `${ROUND9_DIR}/runs/${name}` : a))

/** Every round 8 run in its order, out under the round 9 folder. */
export function round9Runs(): Round6Run[] {
  return round8Runs().map((r) => ({ ...r, argv: retarget(r.argv, r.name) }))
}

/** Sum of round 8's per-model spend, the expected spend. */
export function round9ExpectedUsd(): number {
  return Object.values(R8_MODEL_COST).reduce((sum, c) => sum + c, 0)
}

/** `.sdlc/evals/rounds/2026-10-17-r9-matrix/live-commands.sh`. */
export function round9CommandsScript(): string {
  const lines = [
    '#!/usr/bin/env bash',
    "# T-0326 live round 9: round 8's full matrix again after the round 8 fixes (T-0320 to T-0325), every preset scenario,",
    '# the routing pack and the long flows on three models.',
    '# Generated by `node --experimental-strip-types scripts/e2e-admin/probe/scenarios/round9.ts`; do not hand-edit.',
    `# Spends API credit through the dev proxy (key in .env, never printed). Cap: $${ROUND9_CAP} in total (Kim 2026-10-17).`,
    `#   node --experimental-strip-types scripts/e2e-admin/probe/run-capped.ts --describe ${ROUND9_FILE}`,
    `#   node --experimental-strip-types scripts/e2e-admin/probe/run-capped.ts ${ROUND9_FILE} --cap ${ROUND9_CAP} --round r9-matrix`,
    `# Haiku 5.5 first, then Sonnet 5.5, then Opus 5.5 (expected about $${round9ExpectedUsd().toFixed(2)}, round 8's spend); sample 1.`,
    '# A probe exits 1 when a check fails.',
  ]
  let current = ''
  for (const run of round9Runs()) {
    if (run.model.id !== current) {
      current = run.model.id
      lines.push('', `# ${current}`)
    }
    lines.push(['npm', 'run', 'chat:probe', '--', ...run.argv].map(quote).join(' '))
  }
  return `${lines.join('\n')}\n`
}

if (import.meta.url === `file://${process.argv[1]}`) process.stdout.write(round9CommandsScript())
