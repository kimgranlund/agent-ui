// scripts/e2e-admin/probe/scenarios/round6.ts: live round 6 (T-0294), the full matrix after five rounds of fixes, one
// `live-commands.sh` in `.sdlc/evals/rounds/2026-10-15-r6-matrix/`, run by model (every Haiku run, then Sonnet, then
// Opus) so a stop at the $20 spend cap (`../run-capped.ts`) drops Opus first (Kim 2026-10-16). Every scenario runs on
// all three models, one sample each, in three parts:
//
// - P. Presets: every round scenario of the four shipped presets (`ROUND_PRESETS`: Croupier, Concierge, Lexicographer,
//   Admiral), with round 3's routing oracles (`regressionScenario`) and round 3's `regress-` names, so the matrix
//   lines up with rounds 3 to 5. Lexicographer six-guesses and Admiral concede carry the oracles for the first time;
//   Concierge dinner-at-vela carries none, since its table ask does not start with `Book `.
// - R. The routing pressure pack (`routing.ts`), now on Opus too.
// - L. Every long flow: round 3's blackjack hand and Concierge booking, and round 5's (booking-confirm, spa services,
//   game give-up, facility hours), now on Opus too (rounds 4 and 5 ran them on Haiku and Sonnet only).
//
// Run `node --experimental-strip-types scripts/e2e-admin/probe/scenarios/round6.ts` to print the script;
// `round6.test.mjs` pins the file to this generator.

import { quote } from '../model.ts'
import { ROUND_PRESETS, type RoundModel, type RoundScenario } from './round.ts'
import { LONG_FLOWS, ROUND3_MODELS, regressionScenario, round3Argv } from './round3.ts'
import { ROUND5_LONG_FLOWS } from './round5.ts'
import { ROUTING_SCENARIOS, routingArgv } from './routing.ts'

export const ROUND6_DIR = '.sdlc/evals/rounds/2026-10-15-r6-matrix'
export const ROUND6_FILE = `${ROUND6_DIR}/live-commands.sh`
export const ROUND6_CAP = 20

/** L: round 3's long flows, then round 5's (which holds round 4's). */
export const ROUND6_LONG_FLOWS: ReadonlyArray<{ agent: string; scenario: RoundScenario }> = [...LONG_FLOWS, ...ROUND5_LONG_FLOWS]

export interface Round6Run {
  part: 'preset' | 'routing' | 'long'
  name: string
  agent: string
  model: RoundModel
  argv: string[]
}

const retarget = (argv: string[], name: string): string[] => argv.map((a, i) => (argv[i - 1] === '--out' ? `${ROUND6_DIR}/runs/${name}` : a))

/** Every run in script order: by model (Haiku, Sonnet, Opus), then part (P, R, L), then each part's own order. */
export function round6Runs(): Round6Run[] {
  return ROUND3_MODELS.flatMap((m) => {
    const presets: Round6Run[] = ROUND_PRESETS.flatMap((p) =>
      p.scenarios.map((s) => {
        const name = `regress-${p.agent}-${s.name}-${m.short}-1`
        const scenario = regressionScenario({ agent: p.agent, scenario: s.name, models: [], covers: [] })
        return { part: 'preset' as const, name, agent: p.agent, model: m, argv: retarget(round3Argv(p.agent, scenario, m, name), name) }
      }),
    )
    const routing: Round6Run[] = ROUTING_SCENARIOS.map((s) => {
      const name = `routing-${s.name}-${m.short}-1`
      return { part: 'routing' as const, name, agent: s.agent, model: m, argv: retarget(routingArgv(s, m), name) }
    })
    const long: Round6Run[] = ROUND6_LONG_FLOWS.map(({ agent, scenario }) => {
      const name = `long-${agent}-${scenario.name}-${m.short}-1`
      return { part: 'long' as const, name, agent, model: m, argv: retarget(round3Argv(agent, scenario, m, name), name) }
    })
    return [...presets, ...routing, ...long]
  })
}

/** `.sdlc/evals/rounds/2026-10-15-r6-matrix/live-commands.sh`. */
export function round6CommandsScript(): string {
  const lines = [
    '#!/usr/bin/env bash',
    '# T-0294 live round 6: the full matrix, every preset scenario, the routing pack and the long flows on three models.',
    '# Generated by `node --experimental-strip-types scripts/e2e-admin/probe/scenarios/round6.ts`; do not hand-edit.',
    `# Spends API credit through the dev proxy (key in .env, never printed). Cap: $${ROUND6_CAP} in total (Kim 2026-10-16).`,
    `#   node --experimental-strip-types scripts/e2e-admin/probe/run-capped.ts --describe ${ROUND6_FILE}`,
    `#   node --experimental-strip-types scripts/e2e-admin/probe/run-capped.ts ${ROUND6_FILE} --cap ${ROUND6_CAP} --round r6-matrix`,
    '# Haiku 5.5 first, then Sonnet 5.5, then Opus 5.5; sample 1. A probe exits 1 when a check fails.',
  ]
  let current = ''
  for (const run of round6Runs()) {
    if (run.model.id !== current) {
      current = run.model.id
      lines.push('', `# ${current}`)
    }
    lines.push(['npm', 'run', 'chat:probe', '--', ...run.argv].map(quote).join(' '))
  }
  return `${lines.join('\n')}\n`
}

if (import.meta.url === `file://${process.argv[1]}`) process.stdout.write(round6CommandsScript())
