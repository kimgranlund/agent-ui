// scripts/e2e-admin/probe/scenarios/round7.ts: live round 7 (T-0303), one `live-commands.sh` in
// `.sdlc/evals/rounds/2026-10-16-r7-fails/`. It measures whether the round 6 fixes (T-0296 to T-0302) hold live:
//
// - F. Reruns: every round 6 run whose ledger verdict is fail (`R6_FAILED`, 11 runs), same scenario, model and name,
//   regenerated from the current `round6.ts`.
// - L. Every Haiku long flow, one run each. A long flow that is already a rerun runs once, as the rerun.
//
// Runs go cheapest first by their round 6 cost (`R6_COST`, from `.sdlc/evals/rounds/2026-10-15-r6-matrix/ledger.jsonl`),
// so a stop at the $6 spend cap (`../run-capped.ts`) drops the dearest runs (Kim 2026-10-16).
//
// Run `node --experimental-strip-types scripts/e2e-admin/probe/scenarios/round7.ts` to print the script;
// `round7.test.mjs` pins the file to this generator.

